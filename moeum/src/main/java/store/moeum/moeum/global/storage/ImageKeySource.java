package store.moeum.moeum.global.storage;

import java.util.List;

/**
 * 지금 참조되고 있는 이미지 키를 내놓는 곳. 고아 파일 청소({@link OrphanImageSweepBatch})가 이걸 모아 쓴다.
 *
 * <b>인터페이스로 둔 이유가 안전이다.</b> 청소 배치는 "여기 없는 키 = 고아" 로 판정하고 지운다.
 * 참조처를 한 군데만 빠뜨리면 그게 곧 운영 이미지 삭제다. 배치 안에 목록을 박아 두면
 * 나중에 이미지 컬럼을 추가하는 사람이 그 목록의 존재를 모른 채 지나간다.
 * 구현체를 각 도메인에 두면 이미지를 다루는 코드 옆에 놓이고, 스프링이 알아서 전부 모은다.
 *
 * <b>이미지 키를 저장하는 필드를 새로 만들면 이 인터페이스 구현체도 같이 만든다.</b>
 * 안 만들면 그 이미지는 하루 뒤 지워진다.
 */
public interface ImageKeySource {

	/**
	 * 이 도메인이 참조 중인 S3 객체 키 전부.
	 *
	 * 절대 URL 이 섞여 있어도 그대로 넘긴다 — 버킷 키와 겹치지 않으니 판정에 영향이 없다.
	 * 비어 있는 값은 걸러서 넘긴다.
	 */
	List<String> referencedImageKeys();

	/** 로그에 찍을 이름. 어느 참조처가 몇 건을 냈는지 봐야 사고를 알아챈다 */
	String sourceName();
}
