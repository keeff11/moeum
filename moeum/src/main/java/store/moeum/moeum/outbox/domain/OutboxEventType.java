package store.moeum.moeum.outbox.domain;

/**
 * 밖으로 알릴 사실. <b>전부 이미 확정된 것이다</b> (D-012) —
 * "결제될 예정" 같은 미확정 상태는 여기 들어오지 않는다.
 */
public enum OutboxEventType {

	/** 1차금 결제 완료 */
	ORDER_PAID,

	/**
	 * 2차금을 청구할 수 있게 됐다 — 묶음의 모든 폼이 입고됐다.
	 *
	 * <b>이 알림이 곧 결제 요청이다.</b> 유실되면 구매자는 잔금을 낼 줄 모르고,
	 * 셀러는 미수로 남은 이유를 알 수 없다. 다른 이벤트보다 중요하다.
	 */
	SECOND_PAYMENT_DUE,

	/** 2차금 결제 완료 */
	SECOND_PAID,

	/**
	 * 발송 완료 — 송장번호가 등록됐다 (알림톡 3번 · D-047).
	 *
	 * <b>승인된 템플릿이 아직 없다.</b> 그러면 예전처럼 로그만 남고 SENT 로 넘어간다
	 * (D-040) — 템플릿 id 를 설정에 채우는 순간 나가기 시작한다.
	 */
	SHIPPED,

	/**
	 * 진행 단계가 바뀌었다 — 모집 마감 · 제작 시작 (알림톡 4번 · D-050).
	 *
	 * <b>입고는 여기 들어오지 않는다.</b> 입고 시점에는 이미 2차금 청구 알림
	 * ({@link #SECOND_PAYMENT_DUE})이 나가고, 그 문구가 "입고됐으니 잔금을 내라" 다.
	 * 둘 다 보내면 구매자는 같은 사실을 두 번 받는다.
	 *
	 * payload 의 {@code stage} 로 어느 단계인지 구분한다. 단계마다 타입을 나누지 않은
	 * 것은 알림톡 항목이 "진행 상태 변경" 하나이고, 템플릿도 하나로 승인될 것이기 때문이다.
	 */
	PROGRESS_CHANGED,

	/**
	 * 모집이 성사됐다 — 물건을 받게 됐다 (알림톡 6번 · D-050).
	 *
	 * 목표수량을 채운 경우와 <b>미달이지만 PROCEED 로 진행하는 경우</b>가 같이 온다.
	 * 구매자에게 중요한 것은 목표 달성 여부가 아니라 <b>물건을 받는가</b>이고,
	 * 둘 다 받는다. 미달 여부는 payload 의 {@code shortfall} 로 구분한다.
	 */
	RECRUITMENT_SUCCEEDED,

	/**
	 * 모집이 미달로 끝나 취소됐다 (알림톡 6번 · D-050).
	 *
	 * {@code shortfall_policy = CANCEL} 인 경우다. 성사와 갈라 둔 이유는
	 * <b>구매자가 해야 할 일이 정반대</b>라서다 — 성사는 기다리는 것이고 미달은
	 * 환불을 확인하는 것이다. 문구가 같을 수 없어 템플릿도 갈릴 것이다.
	 *
	 * 템플릿이 하나로 승인되면 설정에서 두 타입에 같은 id 를 넣으면 된다 —
	 * 합쳐 두었다가 나누는 것보다 이쪽이 되돌리기 쉽다.
	 */
	RECRUITMENT_FAILED,

	/**
	 * 2차금이 미납인 채로 남아 있다 — 자동 독촉 (알림톡 8번 · DUE-110 · D-050).
	 *
	 * 청구 알림({@link #SECOND_PAYMENT_DUE})과 다른 타입이다. 그쪽은 "이제 낼 수 있다"
	 * 이고 이쪽은 "아직 안 냈다" 라 문구가 다르다. 셀러의 수동 일괄 청구(S10)는
	 * 여전히 청구 알림을 쓴다.
	 */
	SECOND_PAYMENT_OVERDUE,

	/** 취소·환불 완료 */
	REFUND_COMPLETED
}
