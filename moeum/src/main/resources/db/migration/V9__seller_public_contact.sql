-- 구매자 문의 연락처 (와이어프레임 G12 설정).
--
-- seller 에는 이미 phone 이 있지만 그건 심사·정산 담당자가 연락하는 번호다.
-- 대표자 개인 번호일 수 있어 구매자에게 그대로 내보내면 안 된다.
-- 화면의 '구매자 문의 연락처' 칸은 셀러가 공개하겠다고 적는 값이라 성격이 다르다.
--
-- 전화번호로 형식을 강제하지 않는다. 카카오톡 오픈채팅 링크나 이메일을 적는 셀러가
-- 있을 수 있고, 화면도 자유 입력이다. 노출은 그대로 문자열로 한다.
-- =====================================================================

ALTER TABLE seller
    ADD COLUMN public_contact VARCHAR(100) NULL
        COMMENT '구매자 문의 연락처. 심사용 phone 과 별개로 공개된다';
