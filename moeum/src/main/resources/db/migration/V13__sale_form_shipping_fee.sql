-- V13__sale_form_shipping_fee.sql
-- 판매 폼별 배송비 (D-053).
--
-- 배송비는 셀러 필드 하나였다 (seller.shipping_fee). 같은 셀러가 작은 굿즈와
-- 큰 굿즈를 따로 팔 때 배송비를 달리 받을 길이 없어서 폼에 덮어쓸 자리를 둔다.
--
-- NULL 을 허용한다. NULL 이면 셀러 기본 배송비를 따른다 — 기존 폼과, 배송비를
-- 따로 정하지 않은 폼은 이전과 똑같이 동작한다. 0 은 NULL 이 아니다. 0 은
-- "이 폼은 배송비를 받지 않는다" 는 명시적 값이다.
--
-- 묶음당 1회 원칙은 그대로다 (D-009). 한 묶음에 배송비가 다른 폼이 섞이면
-- 가장 큰 값 하나만 받는다. 무료배송 기준(free_shipping_over)은 셀러 단위로 둔다.
-- =====================================================================

ALTER TABLE sale_form
    ADD COLUMN shipping_fee INT NULL
        COMMENT '폼별 배송비. NULL 이면 셀러 기본 배송비(seller.shipping_fee)를 따른다'
        AFTER min_order_amount;
