-- V4__sale_form_image_key.sql
-- 이미지를 전체 URL 이 아니라 S3 객체 키로 저장한다.
--
-- V3 에서 url VARCHAR(500) 으로 넣었는데, 전체 URL 을 저장하면
-- 버킷 이름을 바꾸거나 나중에 CloudFront 를 앞에 세울 때 쌓인 행을 전부 고쳐야 한다.
-- 키만 두면 응답을 조립하는 코드 한 곳만 바뀐다.
--
-- 아직 이 테이블에 쌓인 행이 없어 데이터 이전이 필요 없다. 지금이 제일 싼 시점이다.
-- =====================================================================

ALTER TABLE sale_form_image
    CHANGE COLUMN url object_key VARCHAR(500) NOT NULL
        COMMENT 'S3 객체 키 (예: sale-forms/12/9f3a....jpg). 전체 URL 을 저장하지 않는다';
