-- V5__shortfall_done.sql
-- 목표수량 미달 처리를 이미 끝냈는지 표시한다.
--
-- 미달 취소는 이미 결제된 돈을 돌려주는 일이라 두 번 돌면 안 된다.
-- "취소되지 않은 주문이 남아 있는가" 로 판정하면 확정 거절된 건을 영원히 다시
-- 시도하게 되고, 결과를 모르는(PROCESSING) 건이 있는 동안 다시 보내면 이중 환불이다.
-- 폼마다 한 번 훑었다는 사실 자체를 남긴다.
--
-- CANCEL 뿐 아니라 PROCEED · EXTEND · 미달 아님도 전부 이 시각을 채운다.
-- 배치가 매분 같은 폼을 다시 집지 않게 하려는 것이 목적이라 정책과 무관하다.
-- =====================================================================

ALTER TABLE sale_form
    ADD COLUMN shortfall_done_at DATETIME(6) NULL
        COMMENT '목표수량 미달 처리를 끝낸 시각. NULL 이면 아직 안 훑었다';

-- 배치가 매분 도는 조회다. CLOSED 이면서 아직 안 훑은 폼만 집는다
CREATE INDEX idx_sale_form_shortfall
    ON sale_form (status, shortfall_done_at);
