-- 택배사 코드 (스마트택배 배송조회 · D-048).
--
-- 송장 등록(D-047)은 택배사를 이름으로만 받았다. 스마트택배 조회 API 가
-- 요구하는 것은 이름이 아니라 코드(t_code)라, 이름만 들고 있으면 조회할 때마다
-- 이름 → 코드 매핑을 어딘가에서 해야 한다. 그 표를 따로 두느니 등록 시점에
-- 코드를 같이 받아 굳힌다.
--
-- 이름을 지우지 않고 둘 다 남기는 이유는 화면 때문이다. 코드만 저장하면
-- 구매자에게 "04" 를 보여 주게 되고, 이름을 얻으려면 매번 택배사 목록 API 를
-- 불러야 한다. 그 API 가 죽으면 이미 발송한 주문의 택배사 이름이 화면에서 사라진다.
-- shipping 은 원래 스냅샷 테이블이다 — 배송지도 같은 이유로 값을 복사해 온다.
--
-- NULL 을 허용한다. 이 마이그레이션 전에 등록된 송장은 코드가 없고, 그 건은
-- 배송조회를 제공하지 않는다(이름은 그대로 보인다). 억지로 채우면 틀린 코드로
-- 남의 배송을 조회하게 된다.
--
-- 길이 10 은 넉넉하다. 스마트택배 택배사 코드는 두 자리 숫자 문자열이다("04").
-- =====================================================================

ALTER TABLE shipping
    ADD COLUMN carrier_code VARCHAR(10) NULL COMMENT '스마트택배 택배사 코드 (t_code)' AFTER carrier;
